def 부호_결정(당사자: str) -> str | None:
    return 당사자_부호.get(당사자)


def 호칭_결정(당사자: str, 심급: str) -> str:
    표 = 심급별_호칭.get(심급, 심급별_호칭["1심"])
    return 표.get(당사자, 당사자)


def 조언(서류종류: str, 당사자: str, 심급: str = "1심",
        반소: bool = False, 다음번호: int | None = None, 가사: bool = False) -> dict:
    """주어진 조건에 대한 추천·주의사항을 구조화하여 반환."""
    정보 = 서류_정보.get(서류종류)
    부호 = 부호_결정(당사자)
    호칭 = 호칭_결정(당사자, 심급)

    결과: dict = {
        "서류종류": 서류종류,
        "당사자": 당사자,
        "심급": 심급,
        "추천_호칭": 호칭,
        "추천_부호": 부호,
        "호증_예시": None,
        "주의사항": [],
        "필수항목": 정보["필수항목"] if 정보 else [],
        "당사자표시": 정보["당사자표시"] if 정보 else "원고 / 피고",
    }

    # 내용증명은 호증 부여 안 함
    if 서류종류 == "내용증명":
        결과["추천_부호"] = None
        결과["호증_예시"] = "해당 없음 (내용증명에는 호증 번호를 붙이지 않습니다)"
    elif 부호:
        n = 다음번호 if 다음번호 else 1
        결과["호증_예시"] = f"{부호} 제{n}호증, {부호} 제{n+1}호증 … (가지번호: {부호} 제{n}호증의 1, 의 2)"

    if 정보:
        결과["주의사항"].extend(정보["주의사항"])

    # 반소 상황 보강
    if 반소 and 서류종류 != "반소장":
        결과["주의사항"].append(
            "반소가 함께 진행 중이라면 부호는 본소 기준을 유지하고 번호를 통합·연속 부여하세요."
        )

    # 심급 보강
    if 심급 in ("항소심", "상고심"):
        결과["주의사항"].append(
            f"{심급}에서도 호증 번호는 1심부터 누적해 이어 붙입니다(다시 1번부터 시작하지 않음)."
        )

    if 가사:
        결과["주의사항"].extend(가사_안내)

    return 결과


def 출력(조언결과: dict) -> None:
    r = 조언결과
    print()
    print("=" * 60)
    print(f"  📋 {r['서류종류']}  ·  당사자: {r['당사자']}  ·  {r['심급']}")
    print("=" * 60)
    print(f"  • 당사자 표시:   {r['당사자표시']}")
    print(f"  • 추천 호칭:     {r['추천_호칭']}")
    if r["추천_부호"]:
        print(f"  • 증거 부호:     {r['추천_부호']}호증  (제출 주체 기준)")
    print(f"  • 호증 번호:     {r['호증_예시']}")
    if r["필수항목"]:
        print(f"  • 필수 항목:     {' · '.join(r['필수항목'])}")
    print("-" * 60)
    print("  ⚠️  용어·번호 주의사항")
    for i, 주의 in enumerate(r["주의사항"], 1):
        print(f"     {i}. {주의}")
    print("=" * 60)
    print("  ※ 본 안내는 실무 관행 참고용이며 법률자문이 아닙니다.")
    print("     개별 사건은 담당 재판부·전자소송 안내를 우선하세요.")
    print()


def main() -> None:
    parser = argparse.ArgumentParser(
        description="법률 서류 용어·증거번호 추천 도우미",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
사용 예시:
  python advisor.py --type 준비서면 --party 피고
  python advisor.py --type 항소장 --party 원고 --instance 항소심
  python advisor.py --type 반소장 --party 피고 --counterclaim
  python advisor.py --type 내용증명 --party 발신인
  python advisor.py --type 준비서면 --party 피고 --next 11   # 11호증부터 부여
        """,
    )
    parser.add_argument("--type", "-t", required=True,
                        help="서류 종류: " + " / ".join(서류_정보.keys()))
    parser.add_argument("--party", "-p", required=True,
                        help="당사자 지위: 원고 / 피고 / 독립당사자참가인 / 보조참가인 / 발신인 / 수신인 등")
    parser.add_argument("--instance", "-i", default="1심",
                        choices=["1심", "항소심", "상고심"], help="심급 (기본: 1심)")
    parser.add_argument("--counterclaim", "-c", action="store_true", help="본소와 반소가 함께 진행 중")
    parser.add_argument("--next", "-N", type=int, default=None, metavar="번호",
                        help="다음에 부여할 호증 시작 번호(예: 직전까지 10호증이면 11)")
    parser.add_argument("--family", "-f", action="store_true", help="가사사건(이혼 등) 보충 안내 추가")
    args = parser.parse_args()

    if args.type not in 서류_정보:
        print(f"오류: 알 수 없는 서류 종류 → {args.type}")
        print("가능한 값: " + " / ".join(서류_정보.keys()))
        sys.exit(1)

    결과 = 조언(args.type, args.party, args.instance,
              반소=args.counterclaim, 다음번호=args.next, 가사=args.family)
    출력(결과)


if __name__ == "__main__":
    main()
